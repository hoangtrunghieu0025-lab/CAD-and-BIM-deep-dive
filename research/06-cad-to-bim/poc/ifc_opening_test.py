import numpy as np, ifcopenshell, ifcopenshell.api as api, ifcopenshell.geom
f = api.run("project.create_file", version="IFC4")
proj = api.run("root.create_entity", f, ifc_class="IfcProject", name="t")
api.run("unit.assign_unit", f)
ctx = api.run("context.add_context", f, context_type="Model")
body = api.run("context.add_context", f, context_type="Model", context_identifier="Body", target_view="MODEL_VIEW", parent=ctx)
site = api.run("root.create_entity", f, ifc_class="IfcSite"); bld = api.run("root.create_entity", f, ifc_class="IfcBuilding")
st = api.run("root.create_entity", f, ifc_class="IfcBuildingStorey", name="L1")
api.run("aggregate.assign_object", f, products=[site], relating_object=proj)
api.run("aggregate.assign_object", f, products=[bld], relating_object=site)
api.run("aggregate.assign_object", f, products=[st], relating_object=bld)
wall = api.run("root.create_entity", f, ifc_class="IfcWall", name="W1")
api.run("geometry.assign_representation", f, product=wall, representation=api.run("geometry.add_wall_representation", f, context=body, length=6.0, height=3.0, thickness=0.2))
api.run("geometry.edit_object_placement", f, product=wall, matrix=np.eye(4))
api.run("spatial.assign_container", f, products=[wall], relating_structure=st)
# lỗ mở: hộp 1.0 x 0.4 x 2.1 đặt tại x=2
op = api.run("root.create_entity", f, ifc_class="IfcOpeningElement", name="OP1")
m = np.eye(4); m[0,3] = 2.0; m[1,3] = 0.0
rep = api.run("geometry.add_wall_representation", f, context=body, length=1.0, height=2.1, thickness=0.4)
api.run("geometry.assign_representation", f, product=op, representation=rep)
api.run("geometry.edit_object_placement", f, product=op, matrix=m)
api.run("feature.add_feature", f, feature=op, element=wall)
door = api.run("root.create_entity", f, ifc_class="IfcDoor", name="D1")
api.run("geometry.edit_object_placement", f, product=door, matrix=m)
api.run("spatial.assign_container", f, products=[door], relating_structure=st)
api.run("feature.add_filling", f, opening=op, element=door)
print("voids:", len(f.by_type("IfcRelVoidsElement")), "fills:", len(f.by_type("IfcRelFillsElement")))
s = ifcopenshell.geom.create_shape(ifcopenshell.geom.settings(), wall)
print("wall verts after opening:", len(s.geometry.verts)//3, "(8 = chưa khoét)")
